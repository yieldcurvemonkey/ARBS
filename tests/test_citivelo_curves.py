r"""Hermetic tests for the Citi Velocity OIS curve builders.

Covers ``MDP/CitiVelocityExcel/curves/``: the per-currency convention table
(``conventions.py``), the rateslib and QuantLib builders (``rl_builder.py``,
``ql_builder.py``) and the par-grid fetch/snapshot layer (``par_grid.py``).

Nothing here needs Excel, a network or a database. The transport is
:class:`MDP.CitiVelocityExcel.testing.FakeExcelApp`; the market data is a
**self-consistent synthetic par grid** built the way ``curves/_smoke.py`` builds
it - a smooth analytic discount curve is chosen, the 44 Velocity par swaps are
priced off it in each currency's own conventions, and those par rates are fed
back to the builders. A correct builder returns a curve that reprices its own
inputs.

What that does and does not prove
---------------------------------
It proves the solve converges and pins its own instruments, and - because the
grid is generated by *rateslib* and one arm of the check reprices it with
*QuantLib* - that the two independent libraries agree about frequency, day
count, payment lag, end-of-month and pillar placement. It does **not** prove the
conventions match the market: the rateslib reprice arm in particular is weakly
circular (the calibrating swap and the grid come from the same ``_make_irs``),
so a wrong day count would cancel out of it. That arm is a convergence check,
not a convention check, and its docstring says so. For the six
``market_standard`` currencies (DKK ILS MXN SGD THB ZAR) nothing hermetic could
establish correctness against the market, and MXN's 28-day Fondeo roll is
knowingly approximated by a monthly schedule.

Several tests are paired with a MUTATION CHECK: the same input is run through a
deliberately-wrong variant and the test asserts the wrong one produces a
different, wrong answer. A round trip that would pass against a metric returning
zeros is not a test, and this package's own history says so - a proxy calendar
would have misdated every ILS roll while every reprice check still tied out.
"""

