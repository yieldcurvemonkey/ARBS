def _zero(t: float) -> float:
    """A smooth Nelson-Siegel-shaped continuously-compounded zero curve."""
    if t <= 0:
        return 0.042
    tau = 3.0
    a = (1.0 - math.exp(-t / tau)) / (t / tau)
    return 0.030 + 0.015 * a + 0.010 * (a - math.exp(-t / tau))


@functools.lru_cache(maxsize=24)
def _synthetic_par_grid(citi_index: str) -> Tuple[Tuple[str, float], ...]:
    """Price the 44 Velocity par swaps off a known curve, in this ccy's conventions.

    Cached because the truth curve carries 660 monthly nodes and pricing 44
    swaps off it costs ~0.1s, which the sweep would otherwise pay per test.
    Returns an immutable pair sequence; callers make their own dict.
    """
    conv = conventions_for(citi_index)
    cal = conv.rl_calendar_object()
    ref = _prev_business_day(_as_ref_date(REF_DATE), cal)
    spot = cal.add_bus_days(ref, int(conv.spot_lag), True)

    nodes = {ref: 1.0}
    for m in range(1, 12 * 55 + 1):
        d = rl.add_tenor(ref, f"{m}M", "f", cal)
        t = (d - ref).days / 365.0
        nodes[d] = math.exp(-_zero(t) * t)
    truth = rl.Curve(
        nodes=nodes,
        id="TRUTH",
        convention=conv.convention,
        calendar=cal,
        modifier="mf",
        interpolation="log_linear",
    )
    return tuple(
        (
            tenor,
            float(
                _make_irs(
                    conv=conv,
                    calendar=cal,
                    effective=spot,
                    tenor=tenor,
                    curve_id="TRUTH",
                    fixed_rate=0.0,
                ).rate(curves=truth)
            ),
        )
        for tenor in TENORS
    )


def _par(citi_index: str = "USD_SOFR") -> Dict[str, float]:
    """A fresh, mutable copy of one currency's synthetic par grid."""
    return dict(_synthetic_par_grid(citi_index))


