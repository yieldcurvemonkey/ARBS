@pytest.mark.slow
def test_cross_backend_forward_agreement_is_bounded_by_calendar_data():
    """Where the two libraries' holidays agree, the forwards agree to 0.01 bp.

    rateslib ships its own 14 calendars and QuantLib its own national ones, and
    nothing reconciles them: for AUD the disagreement moves five of the 44 swap
    maturities by a day, which is the entire 0.067 bp gap on that curve. That is
    calendar data, not a builder bug, so it is bounded loosely rather than
    asserted away - but every calendar-aligned currency is held to 0.01 bp, and
    the misaligned ones are still required to stay inside 0.5 bp, which is far
    tighter than any real convention error would be.
    """
    forwards = [("1Y", "1Y"), ("5Y", "5Y"), ("10Y", "10Y")]
    aligned, misaligned = {}, {}
    for citi_index in sorted(OIS_INDICES):
        par = _par(citi_index)
        rlc = build_rl_ois_curve(par_rates=par, ref_date=REF_DATE, citi_index=citi_index)
        qlc = build_ql_ois_curve(par_rates=par, ref_date=REF_DATE, citi_index=citi_index)
        with qlc.pinned():
            ql_pillars = {
                (d.year(), d.month(), d.dayOfMonth()) for d in (h.pillarDate() for h in qlc.helpers)
            }
        mismatches = [
            tenor
            for tenor, mat in rlc.meta["maturities"].items()
            if (mat.year, mat.month, mat.day) not in ql_pillars
        ]
        gap = max(
            abs(forward_rate(rlc, forward=f, tenor=t) - ql_forward_rate(qlc, forward=f, tenor=t))
            * 100.0
            for f, t in forwards
        )
        (misaligned if mismatches else aligned)[citi_index] = gap

    assert len(aligned) >= 15, f"unexpectedly many misaligned calendars: {sorted(misaligned)}"
    assert max(aligned.values()) < REPRICE_TOL_BP, aligned
    assert not misaligned or max(misaligned.values()) < 0.5, misaligned
