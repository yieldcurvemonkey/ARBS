@pytest.mark.parametrize("citi_index", DEFAULT_CURRENCIES)
def test_rateslib_curve_reprices_its_own_calibration_swaps(citi_index):
    """The rateslib solve pins every one of its 44 instruments to < 0.01 bp.

    Weakly circular by construction, and deliberately so: the synthetic grid is
    priced with the same ``_make_irs`` the builder calibrates with, so a wrong
    day count or payment lag cancels out and this test would not see it. What it
    does see is a solve that did not converge, a misplaced pillar, or a node
    that ended up on a different date from the swap that was supposed to pin it
    - which is what an unconverged curve looks like from the outside. The
    convention check is the QuantLib arm below, which reprices the same grid
    with an independent library.
    """
    rlc = _rl(_par(citi_index), citi_index)
    errors = par_reprice_errors_bp(rlc)
    assert len(errors) == len(TENORS)
    assert float(errors.abs().max()) < REPRICE_TOL_BP
    assert rlc.meta["citi_index"] == citi_index
    assert rlc.rl_pricing_curve_solver.result["status"] == "SUCCESS"


@pytest.mark.parametrize("citi_index", DEFAULT_CURRENCIES)
def test_quantlib_curve_reprices_the_rateslib_generated_grid(citi_index):
    """QuantLib recovers a grid rateslib priced, to < 0.01 bp.

    This is the arm with teeth on conventions: the par rates come out of
    ``rl.IRS`` and go back in through ``ql.OISRateHelper``/``MakeOIS``. The two
    libraries share no code, so a disagreement about frequency, day count,
    payment lag, end-of-month or pillar placement shows up here as a reprice
    error far outside tolerance rather than cancelling out.
    """
    par = _par(citi_index)
    qlc = _ql(par, citi_index)
    errors = ql_par_reprice_errors_bp(qlc, par)
    assert len(errors) == len(TENORS)
    assert float(errors.abs().max()) < REPRICE_TOL_BP
    assert qlc.citi_index == citi_index


@pytest.mark.parametrize("citi_index", DEFAULT_CURRENCIES)
def test_both_backends_anchor_on_the_same_rolled_reference_date(citi_index):
    """A weekend snapshot rolls BACK to the prior business day, identically in both.

    2026-08-08 is a Saturday. GBP settles T+0 and CAD T+1, so if the two
    builders rolled differently the whole curve would shift and every
    cross-backend comparison below would be measuring the wrong thing.
    """
    saturday = datetime.date(2026, 8, 8)
    par = _par(citi_index)
    rlc = build_rl_ois_curve(par_rates=par, ref_date=saturday, citi_index=citi_index)
    qlc = build_ql_ois_curve(par_rates=par, ref_date=saturday, citi_index=citi_index)
    assert rlc.meta["ref_date"].date() == qlc.reference_date
    assert qlc.reference_date < saturday


def test_gbp_settles_t_plus_zero_and_cad_t_plus_one():
    """The spot lag is not uniform, and SONIA is the one that catches people out."""
    usd = _rl(_par("USD_SOFR"), "USD_SOFR")
    gbp = _rl(_par("GBP_SONIA"), "GBP_SONIA")
    cad = _rl(_par("CAD_CORRA"), "CAD_CORRA")
