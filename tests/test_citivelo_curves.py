def _zero_returning_reprice_errors_bp(_curve) -> pd.Series:
    """A repricer that always reports a perfect fit. The thing being mutated in."""
    return pd.Series({t: 0.0 for t in TENORS}, name="reprice_error_bp", dtype=float)


def test_a_reprice_metric_that_returns_zeros_would_pass_the_round_trip(usd_par):
    """MUTATION CHECK for the self-consistency tests above.

    ``build a curve, reprice its own inputs, assert the error is small`` passes
    unconditionally against a metric that returns zeros. So the round trip alone
    proves nothing, and the two tests that follow are what give it teeth: the
    real metrics have to *move* when their input moves.
    """
    rlc = _rl(usd_par)
    broken = _zero_returning_reprice_errors_bp(rlc)
    assert float(broken.abs().max()) < REPRICE_TOL_BP  # the naive assertion, passing on a lie
    assert float(par_reprice_errors_bp(rlc).abs().max()) < REPRICE_TOL_BP


def test_quantlib_reprice_metric_reports_the_bump_it_is_given(usd_par):
    """Repriced against a grid bumped 1 bp on every tenor, the metric reads 1 bp.

    This is the direct teeth for :func:`ql_par_reprice_errors_bp`: it is fed a
    quote set that is deliberately NOT the one the curve was built from, and
    must report the difference on every one of the 44 tenors.
    """
    qlc = _ql(usd_par)
    bumped = {t: v + 0.01 for t, v in usd_par.items()}
    errors = ql_par_reprice_errors_bp(qlc, bumped).abs()
    assert float(errors.min()) == pytest.approx(1.0, abs=0.05)
    assert float(errors.max()) == pytest.approx(1.0, abs=0.05)
    assert float(_zero_returning_reprice_errors_bp(qlc).abs().max()) == 0.0


def test_a_five_bp_quote_bump_moves_the_rebuilt_par_rate_by_five_bp(usd_par):
    """MUTATION CHECK on the builder: the curve must respond to its inputs.

    A builder that ignored ``par_rates`` and returned a flat curve, or a
    ``par_reprice_errors_bp`` that measured the quote against itself, would both
    pass every round trip above. Bumping the 10Y quote by 5 bp and reading the
    rebuilt curve's own 10Y par rate back out is what separates them: it must
    move by 5 bp, and only at that tenor's own quote.
    """
    shifted = dict(usd_par)
    shifted["10Y"] = usd_par["10Y"] + 0.05

    base = _rl(usd_par)
    bumped = _rl(shifted)
    moved = (
        forward_rate(bumped, forward="0D", tenor="10Y")
        - forward_rate(base, forward="0D", tenor="10Y")
    ) * 100.0
    assert moved == pytest.approx(5.0, abs=0.05)

    # The 1Y sits entirely in front of the bumped node, so it must not move.
    unmoved = (
        forward_rate(bumped, forward="0D", tenor="1Y")
        - forward_rate(base, forward="0D", tenor="1Y")
    ) * 100.0
    assert abs(unmoved) < REPRICE_TOL_BP


