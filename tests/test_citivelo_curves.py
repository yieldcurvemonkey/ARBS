def test_asof_takes_the_last_row_at_or_before_the_request(par_grid_frame):
    snap = par_grid_snapshot(par_grid_frame, "2026-07-27 11:30")
    assert snap.name == pd.Timestamp("2026-07-27 11:00")
    assert list(snap.index) == list(par_grid_frame.columns)


def test_nearest_does_look_forward_which_is_why_it_is_not_the_default(par_grid_frame):
    """MUTATION CHECK for the default: ``nearest`` is direction-unbounded.

    11:40 is nearer the 12:00 row than the 11:00 one, so ``nearest`` answers
    with a row from the future while ``asof`` does not. (11:30 would be an exact
    tie and would prove nothing.) A curve built from a future snapshot is not
    wrong in any way a test notices - it is wrong in a way a backtest notices,
    much later, as an implausibly good result. This repo measured ``nearest``
    answering a 00:05 request with a snapshot 55 minutes ahead of it.
    """
    when = pd.Timestamp("2026-07-27 11:40")
    near = par_grid_snapshot(par_grid_frame, when, method="nearest")
    late = par_grid_snapshot(par_grid_frame, when, method="asof")
    assert near.name > when > late.name
    assert near.name == pd.Timestamp("2026-07-27 12:00")


def test_exact_requires_the_timestamp_and_asof_refuses_to_reach_backwards(par_grid_frame):
    assert par_grid_snapshot(
        par_grid_frame, "2026-07-27 11:00", method="exact"
    ).name == pd.Timestamp("2026-07-27 11:00")
    with pytest.raises(ValueError):
        par_grid_snapshot(par_grid_frame, "2026-07-27 11:30", method="exact")
    with pytest.raises(ValueError):
        par_grid_snapshot(par_grid_frame, "2020-01-01")  # before the frame starts
    with pytest.raises(ValueError):
        par_grid_snapshot(par_grid_frame, "2026-07-27 11:00", method="closest")


