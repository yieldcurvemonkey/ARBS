@pytest.mark.parametrize("citi_index", sorted(OIS_INDICES))
def test_every_ql_calendar_and_index_factory_constructs(citi_index):
    """The factories are lazy, so a typo'd class name would surface only at build.

    Six of the indices (SORA NOWA STINA TNDKK SHIR T_FONDEO) have no QuantLib
    class at all and are assembled from ``ql.OvernightIndex``; this walks every
    one of the twenty so a missing class is a test failure rather than a
    currency that silently cannot be built.
    """
    conv = CITI_OIS_CONVENTIONS[citi_index]
    calendar = conv.ql_calendar()
    assert isinstance(calendar, ql.Calendar)

    index = conv.ql_index(ql.YieldTermStructureHandle())
    assert isinstance(index, ql.OvernightIndex)
    assert isinstance(index.fixingCalendar(), ql.Calendar)
    # OISRateHelper takes the FIXED leg day count from the index, so a mismatch
    # here would accrue the fixed leg on the wrong basis with nothing complaining.
    assert index.dayCounter().name() == {
        "act360": "Actual/360",
        "act365f": "Actual/365 (Fixed)",
    }[conv.convention]


@pytest.mark.parametrize(
    "citi_index", sorted(t for t in OIS_INDICES if CITI_OIS_CONVENTIONS[t].rl_spec)
)
def test_specd_currencies_agree_with_rateslib(citi_index):
    """rateslib's named spec is the authority for the fourteen it ships one for.

    Frequency, day count, calendar and payment lag are all read back out of
    ``rl.defaults.spec`` and compared against the table, so a rateslib upgrade
    that changes a spec fails here rather than quietly repricing every
    long-dated curve in that currency.
    """
    conv = CITI_OIS_CONVENTIONS[citi_index]
    spec = rl.defaults.spec[conv.rl_spec]

    assert conv.fixed_frequency == spec["frequency"]
    assert conv.convention == spec["convention"]
    assert conv.rl_calendar == spec["calendar"]
    assert PAYMENT_LAG_BY_INDEX[citi_index] == spec["payment_lag"]
    assert END_OF_MONTH_BY_INDEX[citi_index] == spec["eom"]

    # The accessors re-read the spec themselves and raise on a divergence.
    assert payment_lag_for(citi_index) == spec["payment_lag"]
    assert end_of_month_for(citi_index) == spec["eom"]
    assert conv.approximate is False
    assert conv.provenance == "rateslib_spec"


def test_the_six_unspecd_currencies_are_flagged_and_explained():
    """No rateslib spec means ``approximate=True`` and a note saying what is approximate.

    Silently shipping market-standard conventions as if they were
    library-supplied is the failure this guards: the six are exactly DKK, ILS,
    MXN, SGD, THB and ZAR, and MXN in particular approximates a 28-day Fondeo
    roll with a monthly schedule.
    """
    flagged = {t for t in OIS_INDICES if CITI_OIS_CONVENTIONS[t].approximate}
    assert flagged == MARKET_STANDARD
    for token in sorted(MARKET_STANDARD):
        conv = CITI_OIS_CONVENTIONS[token]
        assert conv.rl_spec is None
        assert conv.rl_calendar is None, "an unspec'd currency must not borrow a proxy calendar"
        assert conv.provenance == "market_standard"
        assert conv.note.strip(), f"{token} is approximate but says nothing about what"
    assert "28-DAY" in CITI_OIS_CONVENTIONS["MXN_T_FONDEO"].note.upper()


