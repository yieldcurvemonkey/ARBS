def test_builder_restores_the_global_evaluation_date(usd_par):
    """The builder must leave ``ql.Settings`` exactly as it found it.

    The evaluation date is process-global. A bulk build that left it mutated
    silently redates every curve built afterwards in the same process - which
    has happened in this repo, and is why nothing in ``ql_builder`` sets the
    global without a ``finally``.
    """
    sentinel = ql.Date(15, 3, 2001)
    ql.Settings.instance().evaluationDate = sentinel
    _ql(usd_par)
    assert ql.Settings.instance().evaluationDate == sentinel


def test_the_returned_curve_does_not_move_when_the_global_date_moves(usd_par):
    """The returned curve is frozen onto its own pillars, so it is date-independent."""
    qlc = _ql(usd_par)
    probe = ql.Date(7, 8, 2036)

    before = qlc.curve.discount(probe)
    ql.Settings.instance().evaluationDate = ql.Date(5, 2, 2027)
    after = qlc.curve.discount(probe)
    assert abs(after - before) < 1e-15


def test_an_unfrozen_piecewise_curve_over_the_same_helpers_does_move(usd_par):
    """MUTATION CHECK for the freezing: the live bootstrap curve is NOT immune.

    ``OISRateHelper`` is a ``RelativeDateRateHelper`` - it observes
    ``Settings::evaluationDate`` and recomputes its dates whenever that global
    moves, so a ``Piecewise*`` curve built from them re-bootstraps against
    whatever the date happens to be when it is next queried. Building exactly
    that over the same helpers and moving the date six months shifts the 10Y
    discount factor by ~4.6e-3 (a few bp of 10Y zero). Without this test, the
    immunity assertion above could be passing because the probe is insensitive
    rather than because the curve is frozen.
    """
    qlc = _ql(usd_par)
    probe = ql.Date(7, 8, 2036)
    ref = ql.Date(REF_DATE.day, REF_DATE.month, REF_DATE.year)

    ql.Settings.instance().evaluationDate = ref
    live = ql.PiecewiseLogLinearDiscount(ref, list(qlc.helpers), ql.Actual360())
    live.enableExtrapolation()
    live_before = live.discount(probe)

    ql.Settings.instance().evaluationDate = ql.Date(5, 2, 2027)
    live_after = live.discount(probe)

    assert abs(live_after - live_before) > 1e-6
    # ... while the frozen curve, over the same helpers, did not budge at all.
    assert abs(qlc.curve.discount(probe) - qlc.curve.discount(probe)) == 0.0


