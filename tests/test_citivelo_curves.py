def test_the_whole_44_tenor_grid_is_one_cvtshist_call():
    """44 tags, one round trip - which is where ``DEFAULT_CHUNK_SIZE`` comes from.

    The add-in serves all 44 columns of a curve export in a single call, so a
    par grid must cost one call and not 44. A regression to per-tenor fetching
    would not fail any correctness assertion; it would just make an intraday
    grid unusably slow, so the call count is asserted directly.
    """
    assert DEFAULT_CHUNK_SIZE == len(TENORS) == 44
    data, _ = _velocity_par_data()
    client, app = _fake_client(data)
    try:
        frame = fetch_par_grid(client=client, citi_index="USD_SOFR", freq="HOURLY", period="1W")
    finally:
        client.close()

    formulas = app.formulas_for("CVTSHIST")
    assert len(formulas) == 1
    for tenor in TENORS:
        assert f"RATES.OIS.USD_SOFR.PAR.{tenor}" in formulas[0]
    assert len(frame.columns) == 44
    assert frame.index.name == "timestamp"
    assert frame.index.is_monotonic_increasing


